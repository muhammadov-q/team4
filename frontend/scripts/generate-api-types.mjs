// Regenerates src/lib/api/schema.ts from the backend's OpenAPI document, so request
// and response types come from the backend instead of being retyped by hand. When the
// backend contract changes, regenerate and let `npm run type-check` show what broke.
//
//   npm run api:types                          # backend running on :8000
//   npm run api:types -- path/to/openapi.json  # or a saved schema file
//   npm run api:check                          # exit 1 when schema.ts is stale
//
// Source, in order: the first CLI argument, $API_SCHEMA_URL, the local backend.

import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const OUT = new URL('../src/lib/api/schema.ts', import.meta.url)
const HEADER =
  '// Generated by `npm run api:types` from the backend OpenAPI schema. Do not edit by hand.\n\n'

const args = process.argv.slice(2)
const check = args.includes('--check')
const source =
  args.find((arg) => !arg.startsWith('--')) ??
  process.env.API_SCHEMA_URL ??
  'http://localhost:8000/openapi.json'
const url = /^https?:\/\//.test(source) ? new URL(source) : pathToFileURL(path.resolve(source))

let generated
try {
  generated = HEADER + astToString(await openapiTS(url))
} catch (err) {
  console.error(`Could not load the OpenAPI schema from ${source}: ${err.message}`)
  console.error('Start the backend (see backend/README.md) or pass a schema file path.')
  process.exit(1)
}

if (check) {
  const current = await readFile(OUT, 'utf8').catch(() => '')
  if (current !== generated) {
    console.error('src/lib/api/schema.ts is out of date with the backend. Run: npm run api:types')
    process.exit(1)
  }
  console.log(`API types match the backend schema (${source}).`)
} else {
  await writeFile(OUT, generated)
  console.log(`Wrote src/lib/api/schema.ts from ${source}`)
}
